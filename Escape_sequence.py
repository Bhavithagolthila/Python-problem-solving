"""
Python Escape Sequences
=======================

Definition:
An escape sequence is a combination of characters that starts with
a backslash (\\) and represents a special character inside a string.

Important Escape Sequences:
1. \\n  - New line
2. \\t  - Horizontal tab
3. \\\\  - Prints a backslash
4. \\"  - Represents a double quote
5. \\'  - Represents a single quote
"""


# Q1. New Line (\n)
# Moves the following text to a new line.

print("Hello\nWorld")

# Output:
# Hello
# World


# Q2. Tab Space (\t)
# Adds horizontal spacing between text.

print("Name:\tBhavi")

# Output:
# Name:   Bhavi


# Q3. Backslash (\\)
# Prints a single backslash.

print("C:\\Users\\Bhavi")

# Output:
# C:\Users\Bhavi


# Q4. Double Quote (\")
# Prints double quotes inside a string.

print("He said \"Hello\"")

# Output:
# He said "Hello"


# Q5. Single Quote (\')
# Prints a single quote inside a string.

print('It\'s Python')

# Output:
# It's Python


# Q6. Multiple Escape Sequences
# We can use multiple escape sequences in one string.

print("Name:\tBhavi\nLanguage:\tPython")

# Output:
# Name:   Bhavi
# Language:   Python


# Important Notes:
# 1. Escape sequences start with a backslash (\).
# 2. \n moves text to a new line.
# 3. \t inserts a horizontal tab.
# 4. \\ prints one backslash.
# 5. input() and escape sequences are different concepts.
# 6. Escape sequences are commonly used in strings and print statements.